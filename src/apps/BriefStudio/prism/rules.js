// BriefStudio · Prism — 수정요청서 "읽는 법" 범용 규칙 (순수 모듈).
// 오상스 전용 프롬프트(promoPrompt.js)에 섞여 있던 규칙 중 어떤 게임·어떤 페이지의 수정요청서에도 통하는 부분을 분리.
// 페이지 전용 슬롯 매핑은 profiles/ 에, 여기는 문서 해석 규칙만. (2026-09 · 사용자 합의: 범용 층 / 프로필 층 분리)
//
// ⚠ promoPrompt.js 의 오상스 규칙 본문은 그대로 보존한다 — 이 파일은 그 문구를 대체하지 않고 범용 추출기(prompts.js)에 주입된다.

export const GENERIC_REVISION_RULES = `[수정요청서 해석 규칙 — 모든 게임·페이지 공통]
- 요청서는 보통 위쪽 "수정 희망 영역"(배너/화면 캡처, 번호 ①②③④ 표시) + 아래쪽 "반영 희망 내용"(변경 표·목록)으로 구성된다.
- "수정 희망 영역" 캡처는 바꾸기 "전"의 옛 화면이다. 거기 보이는 타이틀·상품명·기간은 교체될 옛 값이지 추출할 데이터가 아니다. 새 값은 오직 "반영 희망 내용"의 표/목록에 있다. 둘이 다르면 항상 "반영 희망 내용"을 따른다.
- 표에서 글자색이 빨강(붉은) 계열로 인쇄된 항목은 강조/대표 항목이다. 검정·회색 항목과 구분해 표기한다. 빨강 근거가 없으면 추정하지 않는다.
- "A → B" 표기(텍스트 수정·기간 수정·제목 수정)는 치환 목록으로 뽑는다: before=A, after=B. A 가 없으면 before 를 비우고 uncertain 에 적는다.
- 문서 양식 요소는 데이터가 아니다: 표지 제목("[프로모션] …"), 게임/회사 로고, 팀명·작성자·내선번호·작성일·버전/개정 이력 표, 머리말·꼬리말·페이지 번호. 어떤 슬롯에도 넣지 않는다.
- 수치·날짜·단위·괄호·강화수치(+5~+7)·아이템명은 원문 그대로. 오탈자 교정·유사 단어 대체·요약·창작 금지. 확신이 없으면 비우지 말고 최선 추정 후 uncertain 배열에 사유를 적는다.
- "메인 리소스/배경 변경"처럼 이미지 교체 요청은 텍스트 슬롯에 넣지 않고 uncertain 에 "이미지 교체 요청" 메모로 남긴다.
- "반영 희망 내용"에 명시된 것만 반영한다. 목록에 없는 본문/팝업 데이터를 추정해 채우지 않는다.`;

// 프롬프트 뒤에 범용 규칙 블록을 붙인다 (이미 포함돼 있으면 중복 삽입 안 함).
export function withRevisionRules(prompt) {
  const p = String(prompt || '');
  return p.includes('[수정요청서 해석 규칙') ? p : `${p}\n\n${GENERIC_REVISION_RULES}`;
}
