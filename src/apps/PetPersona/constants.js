/* ───────── 집사 궁합 (결정론) ─────────
   기준: (1) 유형의 추천 집사 목록 포함 여부 (2) 글자 일치 수.
   재미용 점수 — 최대 99. */
export function ownerCompat(type, ownerMbti, types) {
  if (!ownerMbti || !types[type]) return null;
  const best = types[type].owner.includes(ownerMbti);
  let same = 0;
  for (let i = 0; i < 4; i++) if (type[i] === ownerMbti[i]) same++;
  const score = Math.min(99, 57 + same * 7 + (best ? 14 : 0));
  const tier =
    score >= 90 ? { t: "천생연분", c: "이미 서로가 서로의 최애! 지금처럼만 지내면 완벽해요." } :
    score >= 80 ? { t: "환상의 짝꿍", c: "결이 잘 맞는 조합이에요. 서로의 리듬을 존중하면 더 깊어져요." } :
    score >= 70 ? { t: "서로 배우는 사이", c: "다른 점이 있지만 그게 서로를 넓혀줘요. 아이의 속도에 맞춰 주세요." } :
    { t: "반전 케미", c: "정반대라서 오히려 특별한 조합! 아이의 성향 팁을 참고하면 케미가 살아나요." };
  return { score, best, same, ...tier };
}

/* ───────── 검사 기록 (localStorage) ───────── */
const HISTORY_KEY = "pet-persona:history";
const HISTORY_MAX = 8;

export function loadHistory() {
  try {
    const raw = localStorage.getItem(HISTORY_KEY);
    const list = raw ? JSON.parse(raw) : [];
    return Array.isArray(list) ? list : [];
  } catch { return []; }
}

// id·날짜는 여기서 스탬프 — 컴포넌트 렌더 스코프에서 Date 호출 금지(react-hooks/purity).
export function saveHistory(entry) {
  try {
    const now = new Date();
    const stamped = { id: now.getTime(), date: now.toISOString().slice(0, 10), ...entry };
    const list = [stamped, ...loadHistory()].slice(0, HISTORY_MAX);
    localStorage.setItem(HISTORY_KEY, JSON.stringify(list));
    return list;
  } catch { return loadHistory(); }
}

export function removeHistory(id) {
  try {
    const list = loadHistory().filter((e) => e.id !== id);
    localStorage.setItem(HISTORY_KEY, JSON.stringify(list));
    return list;
  } catch { return loadHistory(); }
}
